const root = path.join(__dirname, '..');
const backend = path.join(root, 'backend');
const jobs = new Map();
const stoppingJobs = new Set();
const completedJobs = new Set();
let window;

function pythonBin(requested) { return requested && String(requested).trim() || 'python3'; }
function detectWindowsPython() {
  const localPython = path.join(root, '.venv', 'Scripts', 'python.exe');
  const commands = [localPython, 'python', 'python3', 'py'];
  for (const command of commands) {
    if (command === localPython && !fs.existsSync(localPython)) continue;
    const result = spawnSync(command, ['-c', 'import sys; print(sys.executable)'], {
      encoding: 'utf8', timeout: 5000, windowsHide: true
    });
    const executable = result.status === 0 && result.stdout && result.stdout.trim();
    if (executable) return executable;
  }
  return 'python';
}
function send(payload) { if (window && !window.isDestroyed()) window.webContents.send('job-event', payload); }
function createWindow() {
  window = new BrowserWindow({
    width: 1512, height: 960, minWidth: 1120, minHeight: 700,
    backgroundColor: '#f5f5f1', titleBarStyle: 'hiddenInset',
    webPreferences: { preload: path.join(__dirname, 'preload.cjs'), contextIsolation: true, nodeIntegration: false, sandbox: true }
  });
  if (!app.isPackaged && process.env.VITE_DEV_SERVER_URL) window.loadURL(process.env.VITE_DEV_SERVER_URL);
  else if (!app.isPackaged && process.env.npm_lifecycle_event === 'dev') window.loadURL('http://127.0.0.1:5173');
  else window.loadFile(path.join(root, 'dist', 'index.html'));
}

app.whenReady().then(() => {
  createWindow();
  app.on('activate', () => { if (BrowserWindow.getAllWindows().length === 0) createWindow(); });
});
app.on('window-all-closed', () => { if (process.platform !== 'darwin') app.quit(); });
app.on('before-quit', () => { for (const child of jobs.values()) child.kill('SIGTERM'); });

