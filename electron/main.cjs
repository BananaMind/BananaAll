ipcMain.handle('review-setup-skip', async () => openrouter.finishSetup());
ipcMain.handle('ai-review', async (_e, request) => openrouter.review(request));
ipcMain.handle('training-code', async (_e, configPath, configurationPath, modelingPath) => {
  const source = fs.readFileSync(path.join(backend, 'train.py'), 'utf8');
  const configuration = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  if (!fs.statSync(configurationPath).isFile() || path.extname(configurationPath) !== '.py') throw new Error('Configuration Python file not found');
  if (!fs.statSync(modelingPath).isFile()) throw new Error('Modeling Python file not found');
  for (const [key, file] of [['AutoConfig', configurationPath], ['AutoModelForCausalLM', modelingPath]]) {
    const moduleName = String(configuration.auto_map?.[key] || '').split('.')[0];
    if (moduleName !== path.basename(file, '.py')) throw new Error(`config.json auto_map.${key} must point to ${path.basename(file)}`);
  }
  const summary = JSON.stringify(configuration, null, 2).split('\n').map(line => `# ${line}`).join('\n');
  const header = `# Generated by BananaAll for this custom architecture.\n# Config: ${configPath}\n# Configuration Python: ${configurationPath}\n# Modeling: ${modelingPath}\n# Review the custom loading path in make_model() before running.\n# Configuration supplied for this run:\n${summary}\n\n`;
  return header + source;
});

function runCollect(args, python, timeoutMs = 90000) {
  return new Promise((resolve, reject) => {
    const child = spawn(pythonBin(python), args, { cwd: backend, env: { ...process.env, PYTHONUNBUFFERED: '1' } });
    let stdout = '', stderr = '';
    const timer = setTimeout(() => { child.kill('SIGTERM'); reject(new Error('Python worker timed out.')); }, timeoutMs);
    child.stdout.on('data', d => { stdout += d; });
    child.stderr.on('data', d => { stderr += d; });
    child.on('error', err => { clearTimeout(timer); reject(err); });
    child.on('close', code => {
      clearTimeout(timer);
      if (code !== 0) return reject(new Error(stderr.trim() || stdout.trim() || `Python exited with ${code}`));
      try { resolve(JSON.parse(stdout.trim())); } catch { reject(new Error(stderr.trim() || 'Could not parse dataset preview')); }
    });
  });
}
ipcMain.handle('inspect-dataset', async (_e, source, python) => {
  return runCollect([path.join(backend, 'inspect_dataset.py'), JSON.stringify(source)], python);
});
ipcMain.handle('auth-status', async (_e, python) => runCollect([path.join(backend, 'auth_status.py')], python, 20000));
ipcMain.handle('device-status', async (_e, python) => runCollect([path.join(backend, 'device_status.py')], python, 30000));
ipcMain.handle('export-notebook', async (_e, config, code) => {
  const repositories = validateNotebookConfig(config);
  const auth = await runCollect([path.join(backend, 'export_auth.py'), JSON.stringify(repositories)], config.python, 90000);
  const { script, zipName, tokenEmbedded } = buildNotebook(config, backend, code, auth.token);
  const result = await dialog.showSaveDialog(window, {
    title: 'Save notebook training script',
    defaultPath: path.join(app.getPath('documents'), `${safeName(config.runName)}-notebook.py`),
    filters: [{ name: 'Python script', extensions: ['py'] }]
  });
  if (result.canceled || !result.filePath) return null;
  fs.writeFileSync(result.filePath, script, { encoding: 'utf8', mode: 0o600 });
  if (tokenEmbedded && process.platform !== 'win32') fs.chmodSync(result.filePath, 0o600);
  return { path: result.filePath, zipName, tokenEmbedded, tokenNeeded: auth.tokenNeeded };
});

ipcMain.handle('start-job', async (_e, kind, config, code) => {
  if (!['train', 'evaluate', 'infer'].includes(kind)) throw new Error('Unknown job type');
  const id = crypto.randomUUID();
  const baseDirectory = config.outputDir || path.join(app.getPath('documents'), 'BananaAll', 'runs');
  const runName = safeName(config.runName || `run-${id.slice(0, 8)}`);
  let output = path.resolve(baseDirectory, kind === 'train' ? runName : `job-${id.slice(0, 8)}`);
  if (kind === 'train' && !config.resumeCheckpoint) {
    let suffix = 2;
    while (fs.existsSync(output) && (!fs.statSync(output).isDirectory() || fs.readdirSync(output).length > 0)) {
      output = path.resolve(baseDirectory, `${runName}-${suffix++}`);
    }
  }
  fs.mkdirSync(output, { recursive: true });
  const configFile = path.join(output, 'bananaall-config.json');
  fs.writeFileSync(configFile, JSON.stringify({ ...config, outputPath: output }, null, 2));
  let script = path.join(backend, `${kind}.py`);
  if (kind === 'train' && typeof code === 'string' && code.trim()) {
    script = path.join(output, 'training_code.py');
    fs.writeFileSync(script, code);
  }
  const child = spawn(pythonBin(config.python), [script, configFile], { cwd: backend, env: { ...process.env, PYTHONUNBUFFERED: '1', PYTHONPATH: `${backend}${path.delimiter}${process.env.PYTHONPATH || ''}` } });
  jobs.set(id, child);
  let buffer = '';
  child.stdout.on('data', chunk => {
    buffer += chunk.toString();
    const lines = buffer.split(/\r?\n/);
    buffer = lines.pop();
    for (const line of lines) {
      if (!line.trim()) continue;
      try {
        const event = JSON.parse(line);
        if (event.type === 'complete') completedJobs.add(id);
        send({ id, ...event });
      }
      catch { send({ id, type: 'log', message: line }); }
    }
  });
  child.stderr.on('data', chunk => send({ id, type: 'log', message: chunk.toString() }));
  child.on('error', err => { jobs.delete(id); send({ id, type: 'error', message: err.message }); });
  child.on('close', (code, signal) => {
    jobs.delete(id);
    if (buffer.trim()) send({ id, type: 'log', message: buffer });
    if (!stoppingJobs.has(id) && (signal || code !== 0 || !completedJobs.has(id))) {
      const reason = signal ? `signal ${signal}` : code !== 0 ? `code ${code}` : 'code 0 without a complete event';
      send({ id, type: 'error', message: `${kind} worker exited with ${reason}. Output: ${output}.` });
    }
    send({ id, type: 'exit', code, signal, outputPath: output });
    stoppingJobs.delete(id);
    completedJobs.delete(id);
  });
  return { id, outputPath: output };
});
ipcMain.handle('stop-job', async (_e, id) => {
  const child = jobs.get(id);
  if (!child) return false;
  stoppingJobs.add(id);
  child.kill('SIGTERM');
  return true;
});
